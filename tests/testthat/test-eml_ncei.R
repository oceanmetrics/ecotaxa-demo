test_that("ncei_verify() reports missing, unlisted and mismatched files together, one row each", {
  d <- tempfile(); dir.create(d)
  img <- file.path(d, "img"); dir.create(img)
  for (i in 1:3) writeLines(paste("img", i), file.path(img, sprintf("o%d.jpg", i)))
  b <- ncei_package(file.path(d, "out"), "p4", "2026-11-10", tsv_paths = fixture("export_small.tsv"), image_dir = img)
  expect_equal(ncei_verify(b$bag)$finding, "ok")
  unlink(file.path(b$bag, "data/images/o1.jpg"))
  writeLines("changed", file.path(b$bag, "data/images/o2.jpg"))
  writeLines("new", file.path(b$bag, "data/images/o9.jpg"))
  v <- ncei_verify(b$bag)
  expect_equal(v$finding, c("missing_file", "unlisted_file", "checksum_mismatch"))
  expect_equal(v$path, c("data/images/o1.jpg", "data/images/o9.jpg", "data/images/o2.jpg"))
})
