test_that("ncei_package() keeps the per-sample image folders and counts every image", {
  d <- tempfile(); dir.create(d)
  img <- file.path(d, "exp"); dir.create(file.path(img, "s1"), recursive = TRUE); dir.create(file.path(img, "s2"))
  writeLines("a", file.path(img, "s1", "o1.jpg")); writeLines("b", file.path(img, "s2", "o2.PNG"))
  writeLines("not an image", file.path(img, "export.zip"))
  b <- ncei_package(file.path(d, "out"), "p4", "2026-11-10", tsv_paths = fixture("export_small.tsv"), image_dir = img)
  expect_equal(b$n_images, 2L)
  expect_true(file.exists(file.path(b$bag, "data/images/s1/o1.jpg")))
  expect_true(file.exists(file.path(b$bag, "data/images/s2/o2.PNG")))
  expect_false(file.exists(file.path(b$bag, "data/images/export.zip")))
  expect_equal(ncei_verify(b$bag)$finding, "ok")
})
