  b <- ncei_package(file.path(d, "out"), "p2", "2026-11-06", tsv_paths = tsv, image_dir = img, dwca_zip = zipf,
                    dataset_json = list(organization = "Test Org"))
  expect_equal(b$n_images, 1L); expect_equal(b$n_payload, 4L)
  expect_true(file.exists(file.path(b$bag, "manifest-sha256.txt")))
  expect_equal(ncei_verify(b$bag)$finding, "ok")
  info <- readLines(file.path(b$bag, "bag-info.txt"))
  expect_true(any(grepl("^Payload-Oxum: \\d+\\.4$", info)))
  writeLines("tampered", file.path(b$bag, "data/images/o1.jpg"))
  expect_equal(ncei_verify(b$bag)$finding, "checksum_mismatch")
  file.create(file.path(b$bag, "data/extra.txt"))
  expect_true("unlisted_file" %in% ncei_verify(b$bag)$finding)
})
